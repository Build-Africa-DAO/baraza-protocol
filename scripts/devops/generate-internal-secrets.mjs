#!/usr/bin/env node
// scripts/devops/generate-internal-secrets.mjs
// Standard: S&P 500 Enterprise Fintech / NIST SP 800-63B / Zero-Trust Cryptographic Key Generator
// Generates cryptographically secure high-entropy keys for internal Baraza Protocol microservices.

import { randomBytes, generateKeyPairSync } from 'node:crypto';
import { existsSync, writeFileSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';

console.log('='.repeat(78));
console.log('   BARAZA PROTOCOL — INTERNAL CRYPTOGRAPHIC SECRET GENERATOR');
console.log('   Standard: S&P 500 Enterprise Fintech / NIST SP 800-63B High-Entropy');
console.log('='.repeat(78));

function generateHexSecret(bytes = 32) {
  return randomBytes(bytes).toString('hex');
}

// Generate RFC 8292 VAPID P-256 keypair
function generateVapidKeyPair() {
  const { publicKey, privateKey } = generateKeyPairSync('ec', {
    namedCurve: 'prime256v1',
    publicKeyEncoding: { type: 'spki', format: 'der' },
    privateKeyEncoding: { type: 'pkcs8', format: 'der' },
  });

  // Extract raw uncompressed 65-byte EC point from SPKI DER (last 65 bytes)
  const rawPublic = publicKey.subarray(publicKey.length - 65);
  // Extract raw 32-byte private key from PKCS8 DER (last 32 bytes for secp256r1)
  const rawPrivate = privateKey.subarray(privateKey.length - 32);

  return {
    publicKey: rawPublic.toString('base64url'),
    privateKey: rawPrivate.toString('base64url'),
  };
}

const vapidKeys = generateVapidKeyPair();

const secrets = {
  PAYMENT_PHONE_HASH_PEPPER: {
    value: generateHexSecret(32),
    bits: 256,
    usage: 'HMAC-SHA256 Pepper for Phone Numbers in Payment Dues & Claims',
  },
  PAYMENT_ADAPTER_PROXY_SECRET: {
    value: generateHexSecret(32),
    bits: 256,
    usage: 'Shared secret for internal proxy requests across payment adapters',
  },
  CRON_SECRET: {
    value: generateHexSecret(32),
    bits: 256,
    usage: 'Bearer token for Cloudflare Workers scheduled crons & order sweep',
  },
  ADMIN_SECRET: {
    value: generateHexSecret(32),
    bits: 256,
    usage: 'Master administrative bypass secret for break-glass emergency runs',
  },
  JWT_SECRET: {
    value: generateHexSecret(64),
    bits: 512,
    usage: 'HMAC-SHA512 signing secret for sovereign user session tokens',
  },
  VAPID_PUBLIC_KEY: {
    value: vapidKeys.publicKey,
    bits: 256,
    usage: 'RFC 8292 Uncompressed P-256 Public Key for WebPush notifications',
  },
  VAPID_PRIVATE_KEY: {
    value: vapidKeys.privateKey,
    bits: 256,
    usage: 'RFC 8292 P-256 Scalar Private Key for WebPush notifications',
  },
};

console.log('\nGenerated Zero-Trust Cryptographic Secrets:\n');
for (const [key, meta] of Object.entries(secrets)) {
  console.log(`  ${key.padEnd(32)} [${meta.bits}-bit] : ${meta.value}`);
  console.log(`    ↳ Usage: ${meta.usage}\n`);
}

const shouldWrite = process.argv.includes('--write-env') || process.argv.includes('--output');
const outputPath = resolve('.env.generated');

if (shouldWrite) {
  let envFileContent = `# Auto-generated by scripts/devops/generate-internal-secrets.mjs\n# Date: ${new Date().toISOString()}\n# STANDARD: S&P 500 Enterprise Fintech / NIST SP 800-63B\n\n`;
  for (const [key, meta] of Object.entries(secrets)) {
    envFileContent += `${key}=${meta.value}\n`;
  }
  writeFileSync(outputPath, envFileContent, 'utf8');
  console.log(`✅ Successfully written to: ${outputPath}`);
  console.log(`⚠️  REMINDER: Do NOT commit .env.generated to version control.\n`);
} else {
  console.log('ℹ️  To write these values to .env.generated, run with: node scripts/devops/generate-internal-secrets.mjs --write-env\n');
}

console.log('='.repeat(78));
console.log('   INTERNAL SECRET GENERATION COMPLETE');
console.log('='.repeat(78) + '\n');
